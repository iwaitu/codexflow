export const I18N_DICTIONARIES: Record<DesktopLanguage, Record<I18nKey, string>> = {
  'zh-CN': ZH_CN,
  'en-US': EN_US,
};

export function translate(
  language: DesktopLanguage,
  key: I18nKey,
  params?: Record<string, string | number>,
): string {
  const dict = I18N_DICTIONARIES[language] ?? I18N_DICTIONARIES['zh-CN'];
  let template = dict[key] ?? I18N_DICTIONARIES['zh-CN'][key] ?? key;
  if (params) {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      template = template.replaceAll(`{${paramKey}}`, String(paramValue));
    }
  }
  return template;
}

export function useI18n() {
  const language = usePreferencesStore((s) => s.language);
  const t = (key: I18nKey, params?: Record<string, string | number>) => translate(language, key, params);
  return { language, t };
}
